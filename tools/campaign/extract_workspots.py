"""Builds the list of world workspots other players can be placed on during a scene.

Campaign co-op (stage 4c): while a scene plays, other players' characters sit on free seats
near V when V sits, or take a nearby standing spot with an idle gesture. World spots point at
a .workspot resource by path hash; this picks the suitable ones by their file names, which
follow "<archetype>__<pose>__<action>__<nn>.workspot".

Only the "generic" archetype is used: it fits an average body, like the players' characters.

Input: the file list of the game's archives, from WolvenKit CLI 8.20+:
    WolvenKit.CLI.exe archive "<game>\\archive\\pc\\content" "<game>\\archive\\pc\\ep1" -l -w "*.workspot" > workspots.txt

Usage:
    python tools/campaign/extract_workspots.py workspots.txt code/client/App/World/SceneSpotsData.inl
"""

import sys

SIT_PLACES = {"chair", "couch", "sofa", "barstool", "stool", "bench", "bar", "table", "stairs"}
STAND_PLACES = {"ground", "bar", "wall", "table", "rail", "lean"}
# Poses that would look wrong for a friend standing in on a conversation.
EXCLUDED = ("gun", "rifle", "pistol", "weapon", "aim", "guard", "injur", "cower", "scared", "dead",
            "fight", "cop", "kneel", "crouch", "drunk", "puke", "piss", "sleep", "wounded", "hostage",
            # staff poses: behind the bar or at a work station
            "serve", "work", "clean", "bartend", "cook", "repair", "type", "dj")


def classify(path):
    name = path.rsplit("\\", 1)[-1][: -len(".workspot")].lower()
    parts = name.split("__")
    if len(parts) < 3 or parts[0] != "generic":
        return None
    if any(word in name for word in EXCLUDED):
        return None

    pose = parts[1].split("_")
    if len(pose) < 2:
        return None
    if pose[0] == "sit" and pose[1] in SIT_PLACES:
        return 1
    if pose[0] == "stand" and pose[1] in STAND_PLACES:
        return 2
    return None


def main(listing, output):
    spots = {}
    with open(listing, encoding="utf-8", errors="replace") as source:
        for line in source:
            path = line.strip()
            if path.endswith(".workspot"):
                kind = classify(path)
                if kind:
                    spots[path.lower()] = kind

    with open(output, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/campaign/extract_workspots.py - do not edit.\n")
        out.write("// { path, kind }: 1 = sit, 2 = stand with an idle gesture.\n")
        for path, kind in sorted(spots.items()):
            escaped = path.replace("\\", "\\\\")
            out.write(f'{{"{escaped}", {kind}}},\n')

    sits = sum(1 for kind in spots.values() if kind == 1)
    print(f"{len(spots)} workspots: {sits} sit, {len(spots) - sits} stand")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
